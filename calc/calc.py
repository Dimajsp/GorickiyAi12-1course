print("Калькулятор")
print("=== Строительный калькулятор ===")

while True:
    print("\nВыберите операцию:")
    print("1 - Общая стоимость (количество упаковок × цена)")
    print("2 - Сумма (например, общая длина двух рулонов)")
    print("3 - Разница (сколько материала осталось минус израсходовано)")
    print("4 - Количество упаковок (деление, упаковки могут быть частичными)")
    print("5 - Число полных упаковок (целочисленное деление)")
    print("6 - Остаток материала (остаток от деления)")
    print("7 - Возведение в степень (например, площадь стены)")
    print("0 - Выход")

    choice = input("Ваш выбор: ")

    if choice == "0":
        print("Работа программы завершена.")
        break

    if choice not in ("1", "2", "3", "4", "5", "6", "7"):
        print("Нет такой операции, попробуйте ещё раз.")
        continue

    a = float(input("Введите первое число: "))
    b = float(input("Введите второе число: "))

    # проверка деления на ноль
    if choice in ("4", "5", "6") and b == 0:
        print("Ошибка: деление на ноль невозможно!")
        continue

    if choice == "1":
        result = a * b
        print(f"Общая стоимость: {result:.2f} руб.")
    elif choice == "2":
        result = a + b
        print(f"Сумма: {result}")
    elif choice == "3":
        result = a - b
        print(f"Разница: {result}")
    elif choice == "4":
        result = a / b
        print(f"Количество упаковок: {result:.2f}")
    elif choice == "5":
        result = a // b
        print(f"Число полных упаковок: {int(result)}")
    elif choice == "6":
        result = a % b
        print(f"Остаток материала: {int(result)}")
    else:  # choice == "7"
        result = a ** b
        print(f"Результат возведения в степень: {result}")

    # индивидуальное дополнительное условие
    if result > 100:
        print("Проверьте количество материала!")
        



